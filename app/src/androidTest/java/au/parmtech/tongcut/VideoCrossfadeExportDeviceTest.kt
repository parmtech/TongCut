import java.util.concurrent.TimeUnit

/**
 * Proof-of-pixels for non-destructive crossfades (not just project math).
 * Red foreground dissolves to green background in the same screen PiP slot.
 * CI fixtures are generated by internal-device-pixel-test.yml.
 */
@RunWith(AndroidJUnit4::class)
class VideoCrossfadeExportDeviceTest {
    @Test fun actualEncodedMp4InterpolatesRedToGreenWithoutBlueDip() {
        val app = ApplicationProvider.getApplicationContext<Context>()
        fun fixture(name: String): Uri {
            val f = File(app.cacheDir, "crossfade-$name")
            InstrumentationRegistry.getInstrumentation().context.assets.open(name).use { stream ->
                f.outputStream().use { stream.copyTo(it) }
            }
            assertTrue("Missing test video fixture $name", f.length() > 500)
            return Uri.fromFile(f)
        }
        val red = fixture("overlay_red.mp4")
        val green = fixture("overlay_green.mp4")
        val blue = fixture("main_blue.mp4")
        val graph = LayerTimeline(
            tracks = listOf(TimelineTrack("pip", "PiP", LayerKind.VIDEO, 0)),
            layers = listOf(
                TimelineLayer("a", "pip", LayerKind.VIDEO,
                    startUs=500_000L, durationUs=1_000_000L,
                    sourceUri=red.toString(), sourceDurationUs=3_000_000L),
                TimelineLayer("b", "pip", LayerKind.VIDEO,
                    startUs=1_500_000L, durationUs=1_000_000L,
                    sourceUri=green.toString(), sourceDurationUs=3_000_000L)
            )
        )
        val draft = EditorDraft(
            clips = listOf(DraftClip(blue.toString(), "Blue", durationMs=3_000L)),
            layers = graph
        )
        val blended = VideoCrossfadeEdits.crossfade(draft, "a", "b", 500L)
        val latch = CountDownLatch(1)
        var rendered: Uri? = null
        var failure: String? = null
        Handler(Looper.getMainLooper()).post {
            VideoExporter(app).start(
                clips = listOf(Clip(blue, "Blue", 3_000L)),
                options=ExportOptions(shortSidePixels=720, mute=true),
                overlayLayers=blended.layers,
                onProgress={},
                onSuccess={rendered=it;latch.countDown()},
                onError={failure=it;latch.countDown()}
            )
        }
        assertTrue("Crossfade export timed out", latch.await(240L,TimeUnit.SECONDS))
        assertNull("Crossfade export failed: $failure",failure)
        val file=rendered ?: throw AssertionError("No MP4 saved")
        try {
            MediaMetadataRetriever().use { retriever ->
                retriever.setDataSource(app,file)
                fun colour(atUs: Long): Triple<Int,Int,Int> {
                    val bitmap=retriever.getFrameAtTime(
                        atUs, MediaMetadataRetriever.OPTION_CLOSEST
                    ) ?: throw AssertionError("Missing frame at $atUs")
                    try {
                        // First visual slot: right bottom. Sample the centre,
                        // which must contain a fully coloured red/green PiP.
                        val p=bitmap.getPixel(
                            (bitmap.width*0.79f).toInt(),
                            (bitmap.height*0.76f).toInt()
                        )
                        return Triple(Color.red(p),Color.green(p),Color.blue(p))
                    } finally {bitmap.recycle()}
                }
                val early=colour(750_000L)
                val middle=colour(1_250_000L)
                val late=colour(1_750_000L)
                assertTrue("Expected red before transition: $early", 
                    early.first > early.second + 80 && early.first > early.third + 80)
                assertTrue("Expected green after transition: $late", 
                    late.second > late.first + 80 && late.second > late.third + 80)
                assertTrue("Crossfade missing red/green midpoint: $middle",
                    middle.first > 40 && middle.second > 40 && middle.third < 110)
            }
        } finally {
            app.contentResolver.delete(file,null,null)
        }
    }
}
